#!/usr/bin/env python3
"""Seed reproducible synthetic data for GeoCool's explicitly labeled demo mode.

Nothing generated by this file is a real Nagpur ward boundary, sensor observation,
or remotely-sensed measurement. All records carry provenance='demo_synthetic'.
"""
from __future__ import annotations

import csv
import json
import math
import sqlite3
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
PROCESSED = DATA / "processed"
RAW = DATA / "raw"
DB_PATH = DATA / "geocool_demo.sqlite"
FEATURES = ["lst", "ndvi", "pm", "population", "slope"]
CENTER_LAT, CENTER_LON = 21.1458, 79.0882


def risk_class(risk: float, thresholds: dict | None = None) -> str:
    t = thresholds or {"low_max": 0.25, "moderate_max": 0.5, "high_max": 0.75}
    if risk < t["low_max"]:
        return "Low"
    if risk < t["moderate_max"]:
        return "Moderate"
    if risk < t["high_max"]:
        return "High"
    return "Critical"


def make_demo() -> dict:
    wards = []
    edges = []
    # The coarse rectangles and edge lines are artificial demo geometry only.
    rows, cols = 3, 4
    dlat, dlon = 0.030, 0.035
    for i in range(rows * cols):
        r, c = divmod(i, cols)
        lat0 = CENTER_LAT - rows * dlat / 2 + r * dlat
        lon0 = CENTER_LON - cols * dlon / 2 + c * dlon
        ward_id = f"DEMO-{i + 1:02d}"
        name = ["Zero Mile","Civil Lines","Sadar","Dharampeth","Sitabuldi","Ramdaspeth","Manish Nagar","Nandanvan","Mahal","Wardha Road","Hingna","Mankapur"][i]
        ring = [[lon0,lat0],[lon0+dlon,lat0],[lon0+dlon,lat0+dlat],[lon0,lat0+dlat],[lon0,lat0]]
        wards.append({"ward_id":ward_id,"name":name,"geom":{"type":"Polygon","coordinates":[ring]},"center":{"lat":lat0+dlat/2,"lon":lon0+dlon/2},"provenance":"demo_synthetic"})
        # Spread thermal/vegetation/population/slope values to exercise all classes.
        climate = ((i * 7) % 12) / 11
        base_lst = 34.0 + 10.0 * climate
        base_ndvi = 0.64 - 0.48 * climate
        base_pop = 850.0 + ((i * 941) % 9200)
        base_slope = 0.8 + ((i * 13) % 90) / 18
        if i == 5:
            # A synthetic hot/exposed outlier ensures the demo exercises Critical.
            base_lst, base_ndvi, base_pop, base_slope = 45.0, 0.03, 12000.0, 10.0
        elif i == 10:
            # This separate artificial profile exercises High without being Critical.
            base_lst, base_ndvi, base_pop, base_slope = 42.0, 0.14, 7200.0, 7.5
        for j in range(4):
            lat_a = lat0 + dlat * (0.16 + j * 0.19)
            lon_a = lon0 + dlon * 0.15
            lat_b = lat_a + dlat * 0.12
            lon_b = lon0 + dlon * (0.75 if j % 2 == 0 else 0.84)
            edge_id = f"DEMO-E{i+1:02d}-{j+1:02d}"
            lst = base_lst + (j - 1.5) * 0.65
            ndvi = max(0.03, min(0.9, base_ndvi + (1.5 - j) * 0.035))
            population = base_pop + j * 175
            slope = max(0.1, base_slope + (j - 1.5) * 0.12)
            edges.append({"edge_id":edge_id,"ward_id":ward_id,"lst":round(lst,3),"ndvi":round(ndvi,4),"pm":65.0,"population":round(population,2),"slope":round(slope,3),"start_lat":round(lat_a,7),"start_lon":round(lon_a,7),"end_lat":round(lat_b,7),"end_lon":round(lon_b,7),"geometry_wkt":f"LINESTRING ({lon_a:.7f} {lat_a:.7f}, {lon_b:.7f} {lat_b:.7f})","geom":{"type":"LineString","coordinates":[[lon_a,lat_a],[lon_b,lat_b]]},"provenance":"demo_synthetic"})

    # Reproduce the supplied MinMax-normalized AHP suitability equation exactly.
    normalized = {}
    for feature in FEATURES:
        values = [float(edge[feature]) for edge in edges]
        lo, hi = min(values), max(values)
        normalized[feature] = [(value - lo) / (hi - lo) if hi != lo else 0.0 for value in values]
    for index, edge in enumerate(edges):
        n = {key: normalized[key][index] for key in FEATURES}
        suitability = (1 - n["lst"]) * 0.35 + n["ndvi"] * 0.25 + (1 - n["pm"]) * 0.20 + (1 - n["population"]) * 0.10 + (1 - n["slope"]) * 0.10
        edge["composite_suitability_score"] = round(suitability, 6)
        edge["ahp_suitability"] = round(suitability, 6)
        edge["ahp_risk"] = round(1 - suitability, 6)
        edge["risk_class"] = risk_class(edge["ahp_risk"])

    for ward in wards:
        members = [edge for edge in edges if edge["ward_id"] == ward["ward_id"]]
        mean_risk = sum(edge["ahp_risk"] for edge in members) / len(members)
        ordered = sorted(edge["ahp_risk"] for edge in members)
        ward.update({"edge_count":len(members),"ml_score":round(mean_risk,4),"ahp_score":round(mean_risk,4),"risk_class":risk_class(mean_risk),"mean_risk":round(mean_risk,4),"max_risk":round(max(ordered),4),"p90_risk":round(ordered[min(len(ordered)-1,math.ceil(.9*len(ordered))-1)],4),"provenance":"demo_synthetic"})

    now = datetime.now(timezone.utc)
    alerts = []
    for ward in sorted(wards,key=lambda w:w["mean_risk"],reverse=True)[:5]:
        alerts.append({"id":len(alerts)+1,"ward_id":ward["ward_id"],"ward_name":ward["name"],"ts":(now-timedelta(hours=len(alerts)*3+1)).isoformat(),"severity":ward["risk_class"],"cause":"Synthetic hot-and-low-vegetation demo signal","precaution":"Prioritize shade, hydration access, and targeted field verification.","status":"open","provenance":"demo_synthetic"})
    sensors = []
    for ward in wards[:6]:
        for n in range(4):
            sensors.append({"ward_id":ward["ward_id"],"device_id":f"SIM-{ward['ward_id']}-{n+1}","ts":(now-timedelta(hours=3*n)).isoformat(),"temperature":round(31.5+(n*.65)+(int(ward["ward_id"][-2:])%5),1),"humidity":round(42+(n*3.2),1),"quality":"simulated","provenance":"demo_synthetic"})
    return {"demo":True,"label":"DEMO DATA","generated_at":now.isoformat(),"wards":wards,"edges":edges,"alerts":alerts,"sensor_readings":sensors,"model_runs":[],"thresholds":{"low_max":0.25,"moderate_max":0.5,"high_max":0.75},"ahp_weights":{"lst":0.35,"ndvi":0.25,"pm":0.20,"population":0.10,"slope":0.10},"provenance":"demo_synthetic"}


def seed_sqlite(payload: dict) -> None:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(DB_PATH) as con:
        con.executescript("""
        PRAGMA foreign_keys=ON;
        CREATE TABLE IF NOT EXISTS wards(ward_id TEXT PRIMARY KEY,name TEXT NOT NULL,geom TEXT NOT NULL,provenance TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS edges(edge_id TEXT PRIMARY KEY,ward_id TEXT NOT NULL,geom TEXT NOT NULL,lst REAL,ndvi REAL,pm REAL,population REAL,slope REAL,ahp_suitability REAL,ahp_risk REAL,geometry_wkt TEXT,start_lat REAL,start_lon REAL,end_lat REAL,end_lon REAL,provenance TEXT NOT NULL,FOREIGN KEY(ward_id) REFERENCES wards(ward_id));
        CREATE TABLE IF NOT EXISTS risk_scores(id INTEGER PRIMARY KEY AUTOINCREMENT,ward_id TEXT NOT NULL,edge_id TEXT,ts TEXT NOT NULL,ml_score REAL,ml_class TEXT,ahp_score REAL,ahp_class TEXT,contributions TEXT,provenance TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS model_runs(id INTEGER PRIMARY KEY AUTOINCREMENT,algo TEXT,trained_at TEXT,params TEXT,accuracy REAL,precision REAL,recall REAL,f1 REAL,rmse REAL,mae REAL,r2 REAL,confusion_matrix TEXT,provenance TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS alerts(id INTEGER PRIMARY KEY,ward_id TEXT,ts TEXT,severity TEXT,cause TEXT,precaution TEXT,status TEXT,provenance TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS sensor_readings(id INTEGER PRIMARY KEY AUTOINCREMENT,ward_id TEXT,device_id TEXT,ts TEXT,temperature REAL,humidity REAL,quality TEXT,provenance TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS pipeline_runs(id INTEGER PRIMARY KEY AUTOINCREMENT,job TEXT,started_at TEXT,finished_at TEXT,status TEXT,log TEXT);
        CREATE TABLE IF NOT EXISTS app_settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
        """)
        con.execute("DELETE FROM risk_scores"); con.execute("DELETE FROM edges"); con.execute("DELETE FROM wards"); con.execute("DELETE FROM alerts"); con.execute("DELETE FROM sensor_readings")
        for ward in payload["wards"]:
            con.execute("INSERT INTO wards(ward_id,name,geom,provenance) VALUES(?,?,?,?)",(ward["ward_id"],ward["name"],json.dumps(ward["geom"]),"demo_synthetic"))
        for edge in payload["edges"]:
            con.execute("INSERT INTO edges(edge_id,ward_id,geom,lst,ndvi,pm,population,slope,ahp_suitability,ahp_risk,geometry_wkt,start_lat,start_lon,end_lat,end_lon,provenance) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",(edge["edge_id"],edge["ward_id"],json.dumps(edge["geom"]),edge["lst"],edge["ndvi"],edge["pm"],edge["population"],edge["slope"],edge["ahp_suitability"],edge["ahp_risk"],edge["geometry_wkt"],edge["start_lat"],edge["start_lon"],edge["end_lat"],edge["end_lon"],"demo_synthetic"))
        for alert in payload["alerts"]:
            con.execute("INSERT INTO alerts(id,ward_id,ts,severity,cause,precaution,status,provenance) VALUES(?,?,?,?,?,?,?,?)",(alert["id"],alert["ward_id"],alert["ts"],alert["severity"],alert["cause"],alert["precaution"],alert["status"],"demo_synthetic"))
        for reading in payload["sensor_readings"]:
            con.execute("INSERT INTO sensor_readings(ward_id,device_id,ts,temperature,humidity,quality,provenance) VALUES(?,?,?,?,?,?,?)",(reading["ward_id"],reading["device_id"],reading["ts"],reading["temperature"],reading["humidity"],reading["quality"],"demo_synthetic"))
        for key,value in [("thresholds",payload["thresholds"]),("demo_mode",True)]:
            con.execute("INSERT OR REPLACE INTO app_settings(key,value) VALUES(?,?)",(key,json.dumps(value)))


def main() -> None:
    RAW.mkdir(parents=True,exist_ok=True); PROCESSED.mkdir(parents=True,exist_ok=True)
    payload = make_demo()
    (DATA/"demo_data.json").write_text(json.dumps(payload,indent=2),encoding="utf-8")
    csv_path = PROCESSED/"edge_suitability.csv"
    columns = ["edge_id","lst","ndvi","pm","population","slope","composite_suitability_score","geometry_wkt","start_lat","start_lon","end_lat","end_lon"]
    with csv_path.open("w",newline="",encoding="utf-8") as f:
        writer=csv.DictWriter(f,fieldnames=columns); writer.writeheader()
        for edge in payload["edges"]: writer.writerow({key:edge.get(key) for key in columns})
    seed_sqlite(payload)
    print(f"Seeded {len(payload['wards'])} DEMO wards, {len(payload['edges'])} DEMO edges, {len(payload['alerts'])} DEMO alerts, and {len(payload['sensor_readings'])} DEMO sensor readings.")
    print(f"DEMO DATA only; CSV: {csv_path}; SQLite: {DB_PATH}")

if __name__ == "__main__":
    main()
